"""Render Card Glicko CSV exports as context/card-ratings.md.

Usage: render-card-ratings.py <csv-dir> <fetched-date>
"""

import csv
import sys
from pathlib import Path

SHEET = "https://docs.google.com/spreadsheets/d/1CaVOd1pgAgmjJHXPM1tVMVnlJOLDZaq8BxjW4I1NI1E"

TABLES = [
    ("cards", "Kingdom cards"),
    ("events-projects", "Events and Projects"),
    ("ways", "Ways"),
    ("landmarks", "Landmarks"),
    ("traits", "Traits"),
    ("prophecies", "Prophecies"),
    ("allies", "Allies"),
]


def read(path):
    with open(path, newline="") as f:
        rows = list(csv.reader(f))
    header = rows[0]
    updated = header[-1].strip() if header[-2].startswith("Last Update") else ""
    entries = []
    for row in rows[1:]:
        if len(row) < 10 or not row[1].strip():
            continue
        entries.append((row[1].strip(), float(row[2]), row[9].strip() == "deprecated"))
    entries.sort(key=lambda e: -e[1])
    return updated, entries


def table(entries):
    lines = ["| Card | Rating |", "| --- | ---: |"]
    lines += [f"| {name} | {rating:.1f} |" for name, rating, _ in entries]
    return "\n".join(lines)


def main():
    src, fetched = Path(sys.argv[1]), sys.argv[2]
    data = {name: read(src / f"{name}.csv") for name, _ in TABLES}
    updated = data["cards"][0]

    out = [
        "# Card Ratings",
        "",
        f"Community [Dominion Card Glicko]({SHEET}) ratings. Higher is",
        "stronger. Generated by `just refresh-power`; don't edit by hand.",
        f"Fetched {fetched}; the sheet was last updated {updated}.",
        "",
        "How to read these numbers is in `context/card-power.md`.",
    ]
    for name, title in TABLES:
        entries = data[name][1]
        current = [e for e in entries if not e[2]]
        old = [e for e in entries if e[2]]
        out += ["", f"## {title}", "", table(current)]
        if old:
            out += [
                "",
                f"### {title}: first edition only",
                "",
                "Few raters still compare these, so the ratings are rough.",
                "",
                table(old),
            ]
    print("\n".join(out))


if __name__ == "__main__":
    main()
